// 미리보기를 캡처한다. 사용: electron shoot-card.js <Comp> [너비=960]
// shots/<Comp>.png 와 shots/<Comp>.log(콘솔 오류, 못 불러온 파일)를 남긴다.
const { app, BrowserWindow } = require('electron')
const fs = require('fs')
const path = require('path')
const args = process.argv.slice(process.argv.findIndex((a) => a.endsWith('shoot-card.js')) + 1)
const comp = args[0]
const width = Number(args[1] || 960)
const logFile = path.join(__dirname, 'shots', comp + '.log')
fs.mkdirSync(path.dirname(logFile), { recursive: true })
fs.writeFileSync(logFile, '')
const log = (...a) => fs.appendFileSync(logFile, a.join(' ') + '\n')
setTimeout(() => { log('error timeout'); app.quit() }, 30000)
app.setPath('userData', path.join(require('os').tmpdir(), 'llp-card-' + process.pid))
app.disableHardwareAcceleration()
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width, height: 600, useContentSize: true, webPreferences: { offscreen: true } })
  win.webContents.on('console-message', (e, level, msg) => { if (level >= 2 && !msg.includes('Electron Security Warning')) log('console', msg) })
  win.webContents.session.webRequest.onCompleted((d) => { if (d.statusCode >= 400) log('http', d.statusCode, d.url) })
  await win.loadURL('http://localhost:5299/card/' + comp)
  await win.webContents.executeJavaScript('document.fonts.ready.then(() => true)')
  await new Promise((r) => setTimeout(r, 400))
  const h = await win.webContents.executeJavaScript('Math.ceil(Math.max(document.documentElement.scrollHeight, document.body.scrollHeight))')
  win.setContentSize(width, Math.min(h, 4000))
  await new Promise((r) => setTimeout(r, 500))
  const img = await win.webContents.capturePage()
  fs.writeFileSync(path.join(__dirname, 'shots', comp + '.png'), img.toPNG())
  log('ok', width + 'x' + h)
  app.quit()
})
